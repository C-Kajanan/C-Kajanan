// Generates the skill's tool reference and tool list from src/tools.ts, so
// the skill and the MCP server always describe the same tools.
//   npm run gen-skill          write skill/autocad/reference.md + scripts/tools.json
//   npm run gen-skill -- --check   fail if they are out of date (used by npm test)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import { tools } from "../build/tools.js";

const skillDir = fileURLToPath(new URL("../../skill/autocad/", import.meta.url));
const check = process.argv.includes("--check");

function typeOf(s) {
  if (!s) return "any";
  if (s.enum) return s.enum.map((v) => `\`${v}\``).join(" \\| ");
  if (s.anyOf) return s.anyOf.map(typeOf).join(" \\| ");
  if (s.type === "array") return `${typeOf(s.items)}[]`;
  if (s.type === "object") {
    if (s.properties?.x && s.properties?.y) return "point";
    if (s.properties) return `{ ${Object.keys(s.properties).join(", ")} }`;
    return "{ [key]: string }";
  }
  return s.type ?? "any";
}

const sections = [];
const index = [];
for (const tool of tools) {
  const schema = z.toJSONSchema(z.object(tool.input), { io: "input" });
  const props = schema.properties ?? {};
  const required = new Set(schema.required ?? []);
  const flags = [tool.readOnly && "read-only", tool.destructive && "destructive, needs --confirm", tool.image && "returns a PNG"]
    .filter(Boolean)
    .join(", ");
  let md = `### \`${tool.name}\`${flags ? ` _(${flags})_` : ""}\n\n${tool.description}\n`;
  const names = Object.keys(props);
  if (names.length > 0) {
    md += "\n| Param | Type | Default | Notes |\n| --- | --- | --- | --- |\n";
    for (const name of names) {
      const p = props[name];
      const def = p.default !== undefined ? `\`${JSON.stringify(p.default)}\`` : required.has(name) ? "**required**" : "";
      md += `| \`${name}\` | ${typeOf(p)} | ${def} | ${(p.description ?? "").replace(/\|/g, "\\|")} |\n`;
    }
  }
  sections.push(md);
  index.push({ name: tool.name, readOnly: !!tool.readOnly, destructive: !!tool.destructive, image: !!tool.image });
}

const reference = `# AutoCAD tool reference

<!-- Generated by server/scripts/gen-skill.mjs from server/src/tools.ts. Do not edit by hand. -->

Call any tool with \`node scripts/acad.mjs <tool> '<json params>'\`. A \`point\` is \`{"x":0,"y":0,"z":0}\` in drawing units (\`z\` is optional). Angles are degrees counter-clockwise from +X. Entities are identified by their handle, a hex string like \`"2A3F"\`.

${sections.join("\n")}`;
const list = JSON.stringify(index, null, 2) + "\n";

const outputs = [
  [skillDir + "reference.md", reference],
  [skillDir + "scripts/tools.json", list],
];
let stale = false;
for (const [path, content] of outputs) {
  let current = null;
  try { current = readFileSync(path, "utf8"); } catch {}
  if (current === content) continue;
  if (check) { console.error(`${path} is out of date. Run: npm run gen-skill`); stale = true; }
  else { writeFileSync(path, content); console.log(`wrote ${path}`); }
}
if (stale) process.exit(1);
